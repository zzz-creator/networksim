$("btnExport").onclick = async () => {
  saveDB();
  const json = JSON.stringify(DB, null, 2);
  const fname =
    (DB.meta.name || "topologie").replace(/[^\w\-]+/g, "_") + ".json";

  if (window.showSaveFilePicker) {
    try {
      const handle = await window.showSaveFilePicker({
        suggestedName: fname,
        types: [
          {
            description: "JSON topologie",
            accept: { "application/json": [".json"] },
          },
        ],
      });
      const w = await handle.createWritable();
      await w.write(json);
      await w.close();
      setStatus(t("stSaved") + ": " + handle.name);
      return;
    } catch (err) {
      if (err && err.name === "AbortError") {
        setStatus(t("stExportCanceled"));
        return;
      }
    }
  }

  const blob = new Blob([json], { type: "application/json" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = fname;
  a.click();
  URL.revokeObjectURL(a.href);
  setStatus(t("stExportFallback"));
};
$("btnImport").onclick = () => $("fileInput").click();
$("fileInput").onchange = (e) => {
  const f = e.target.files[0];
  if (!f) return;
  if (f.size > 20 * 1024 * 1024) {
    setStatus(t("stImportTooBig"), false);
    e.target.value = "";
    return;
  }
  const r = new FileReader();
  r.onload = () => {
    const prevDB = DB,
      prevName = $("topoName").value;
    try {
      const parsed = JSON.parse(r.result);
      if (
        !Array.isArray(parsed.devices) ||
        !Array.isArray(parsed.segments) ||
        !Array.isArray(parsed.links)
      )
        throw new Error("invalid structure");
      DB = parsed;
      if (!DB.meta) DB.meta = { name: t("stImported"), version: 1 };
      migrateDB();
      $("topoName").value = DB.meta.name || t("stImported");
      render();
      saveDB();
      refreshAll();
      fitView();
      setStatus(t("stImported") + ": " + f.name);
    } catch (err) {
      DB = prevDB;
      $("topoName").value = prevName;
      try {
        render();
        refreshAll();
      } catch (e2) {}
      setStatus(t("stImportError"), false);
    }
  };
  r.readAsText(f);
  e.target.value = "";
};
