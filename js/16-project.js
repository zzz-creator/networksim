function buildPresetMenu() {
  const p = $("presetPanel");
  const presets = getPresets();
  p.innerHTML = presets
    .map(
      (pr, i) =>
        `<button class="preset-item" data-p="${i}">${icon(pr.ico, "ico-a")}${esc(pr.name)}<small>${esc(pr.short || pr.desc || "")}</small></button>`,
    )
    .join("");
  p.querySelectorAll(".preset-item").forEach(
    (b) =>
      (b.onclick = () => {
        p.classList.remove("open");
        const pr = getPresets()[+b.getAttribute("data-p")];
        if (pr.bullets) openPresetInfo(pr);
        else loadPreset(pr);
      }),
  );
}
function openPresetInfo(pr) {
  openModal(`
    <h2 style="font-family:var(--mono)">${icon(pr.ico, "ico-a")}${esc(pr.name)}</h2>
    <ul class="ab-road" style="margin-bottom:14px">${pr.bullets.map((b) => `<li><span>${esc(b)}</span></li>`).join("")}</ul>
    <div style="display:flex;justify-content:flex-end;gap:9px">
      <button class="btn" id="piClose">${t("fbCancel")}</button>
      <button class="btn primary" id="piLoad">${t("presetLoadBtn")}</button>
    </div>`);
  $("piClose").onclick = closeModal;
  $("piLoad").onclick = () => {
    closeModal();
    loadPreset(pr);
  };
}

